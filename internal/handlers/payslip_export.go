func companyAddress(c models.Company, lang string) string {
	if lang == "bn" && c.AddressBn != "" {
		return c.AddressBn
	}
	return c.AddressEn
}

func paymentMethodName(acctType string, labels payslipLabels) string {
	switch strings.ToLower(acctType) {
	case "bank", "bank_transfer", "bank-transfer":
		return labels.BankTransfer
	case "cash":
		return labels.Cash
	case "mobile", "mobile_banking", "bkash", "nagad", "rocket":
		return labels.MobileBanking
	case "cheque", "check":
		return labels.Cheque
	default:
		if acctType == "" {
			return labels.BankTransfer
		}
		return acctType
	}
}

func shortPayrollNo(id string) string {
	if len(id) > 10 {
		return strings.ToUpper(id[:10])
	}
	return strings.ToUpper(id)
}

