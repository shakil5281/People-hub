// PayslipExport godoc
//
// @Summary      Export payslip(s) to Excel
// @Description  Export a single employee payslip or payslips for all employees in the month as Excel. 4 payslips per A4 page.
// @Tags         Salary
// @Security     BearerAuth
// @Produce      application/vnd.openxmlformats-officedocument.spreadsheetml.sheet
// @Param        company_id     query string false "Company ID (required for all employees)"
// @Param        employee_id    query string false "Employee ID (single payslip)"
// @Param        month          query int    true  "Month (1-12)"
// @Param        year           query int    true  "Year"
// @Param        lang           query string false "Language: en|bn (default en)"
// @Param        department_id  query string false "Filter by department"
// @Param        section_id     query string false "Filter by section"
// @Param        designation_id query string false "Filter by designation"
// @Param        line_id        query string false "Filter by line"
// @Param        group_id       query string false "Filter by group"
// @Success      200  {file}  file
// @Failure      400  {object}  map[string]string
// @Failure      500  {object}  map[string]string
// @Router       /salary/payslip/export [get]
func (h *SalaryHandler) PayslipExport(c *gin.Context) {
	month, year, ok := payslipExportParams(c)
	if !ok {
		return
	}

	lang := c.DefaultQuery("lang", "en")
	if lang != "bn" {
		lang = "en"
	}

	if employeeID := c.Query("employee_id"); employeeID != "" {
		salary, err := h.salaryRepo.FindByEmployeeMonth(employeeID, month, year)
		if err != nil {
			c.JSON(http.StatusNotFound, gin.H{"error": "Salary not found for this employee/month"})
			return
		}
		exportSinglePayslipExcel(c, salary, month, year, lang)
		return
	}

	companyID := c.Query("company_id")
	if companyID == "" {
		c.JSON(http.StatusBadRequest, gin.H{"error": "company_id is required for all-employee export"})
		return
	}

	salaries, err := h.salaryRepo.ListAllByMonthFiltered(repository.SalaryFilter{
		CompanyID:     companyID,
		Month:         month,
		Year:          year,
		DepartmentID:  c.Query("department_id"),
		SectionID:     c.Query("section_id"),
		DesignationID: c.Query("designation_id"),
		LineID:        c.Query("line_id"),
		GroupID:       c.Query("group_id"),
	})
	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		return
	}
	if len(salaries) == 0 {
		c.JSON(http.StatusNotFound, gin.H{"error": "No salary records found for this month"})
		return
	}

	exportBulkPayslipExcel(c, salaries, month, year, lang)
}

