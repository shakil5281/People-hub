func monthName(month int, lang string) string {
	if lang == "bn" {
		return bnMonthNames[month]
	}
	return time.Date(2000, time.Month(month), 1, 0, 0, 0, 0, time.UTC).Format("January")
}

func buildPayslipLabels(lang string, company models.Company) payslipLabels {
	labels := enLabels
	if lang == "bn" {
		labels = bnLabels
	}
	if company.ID != "" {
		if lang == "bn" && company.CompanyNameBn != "" {
			labels.CompanyName = company.CompanyNameBn
		} else {
			labels.CompanyName = company.CompanyNameEn
		}
	}
	if labels.CompanyName == "" {
		labels.CompanyName = labels.PayslipWord
	}
	return labels
}

func formatBdNumber(v float64) string {
	parts := strings.Split(fmt.Sprintf("%.2f", v), ".")
	intPart := parts[0]
	var result strings.Builder
	count := 0
	for i := len(intPart) - 1; i >= 0; i-- {
		result.WriteByte(intPart[i])
		count++
		if count%3 == 0 && i > 0 {
			result.WriteByte(',')
		}
	}
	runes := []rune(result.String())
	for i, j := 0, len(runes)-1; i < j; i, j = i+1, j-1 {
		runes[i], runes[j] = runes[j], runes[i]
	}
	return string(runes) + "." + parts[1]
}

func fmtMoney(v float64) string {
	r := formatBdNumber(v)
	if strings.HasSuffix(r, ".00") {
		r = r[:len(r)-3]
	}
	return r
}

func loadBanglaFont(pdf *gofpdf.Fpdf) string {
	if pdf == nil {
		return "Arial"
	}
	candidates := []struct {
		path string
		bold string
	}{
		{"C:\\Windows\\Fonts\\SutonnyMJ.ttf", "C:\\Windows\\Fonts\\SutonnyMJ-Bold.ttf"},
	}
	for _, cand := range candidates {
		if _, err := os.Stat(cand.path); err != nil {
			continue
		}
		if _, err := os.Stat(cand.bold); err != nil {
			continue
		}
		pdf.AddUTF8Font("Bangla", "", cand.path)
		if pdf.Error() != nil {
			continue
		}
		pdf.AddUTF8Font("Bangla", "B", cand.bold)
		if pdf.Error() != nil {
			continue
		}
		return "Bangla"
	}
	pdf.AddUTF8FontFromBytes("Bangla", "", notoSansBengaliRegular)
	pdf.AddUTF8FontFromBytes("Bangla", "B", notoSansBengaliBold)
	if pdf.Error() == nil {
		return "Bangla"
	}
	return "Arial"
}

