func sanitizeSheetName(name string) string {
	replacer := strings.NewReplacer("[", "", "]", "", ":", "", "*", "", "?", "", "/", "", "\\", "")
	name = replacer.Replace(name)
	name = strings.TrimSpace(name)
	if len(name) > 31 {
		name = name[:31]
	}
	return name
}

func renderJobCardExcel(c *gin.Context, startDate, endDate string, sections []jobCardSection) {
	f := excelize.NewFile()
	defer f.Close()

	company := models.Company{}
	if len(sections) > 0 && len(sections[0].Rows) > 0 {
		company = sections[0].Rows[0].Employee.Company
	}
	companyName := companyDisplayName(company)
	period := jobCardPeriod(startDate, endDate)

	if len(sections) == 0 {
		sections = []jobCardSection{{Employee: models.Employee{}}}
	}

	for i, sec := range sections {
		sheetName := sanitizeSheetName(sec.Employee.EmployeeID)
		if sheetName == "" {
			sheetName = fmt.Sprintf("JobCard%d", i+1)
		}
		if i == 0 {
			f.SetSheetName("Sheet1", sheetName)
		} else {
			f.NewSheet(sheetName)
		}
		fillJobCardSheet(f, sheetName, companyName, period, sec)

		orientation := "portrait"
		paperSize := 9
		fitW := 1
		fitH := 0
		f.SetPageLayout(sheetName, &excelize.PageLayoutOptions{
			Orientation: &orientation, Size: &paperSize, FitToWidth: &fitW, FitToHeight: &fitH,
		})
		f.SetPageMargins(sheetName, &excelize.PageLayoutMarginsOptions{
			Left:   float64Ptr(0.3), Right: float64Ptr(0.3),
			Top:    float64Ptr(0.4), Bottom: float64Ptr(0.4),
			Header: float64Ptr(0), Footer: float64Ptr(0),
		})
		f.SetSheetView(sheetName, -1, &excelize.ViewOptions{ShowGridLines: boolPtr(false)})
	}
	f.SetActiveSheet(0)

	filename := fmt.Sprintf("job_cards_%s_%s.xlsx", startDate, endDate)
	if len(sections) == 1 {
		filename = fmt.Sprintf("job_card_%s_%s_%s.xlsx", sections[0].Employee.EmployeeID, startDate, endDate)
	}
	c.Header("Content-Type", "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet")
	c.Header("Content-Disposition", fmt.Sprintf("attachment; filename=%s", filename))
	f.Write(c.Writer)
}

func float64Ptr(f float64) *float64 { return &f }
func boolPtr(b bool) *bool          { return &b }

func fillJobCardSheet(f *excelize.File, sheet, companyName, period string, sec jobCardSection) {
	cols := []struct {
		header string
		width  float64
	}{
		{"#", 5},
		{"Date", 14},
		{"Day", 8},
		{"Shift", 16},
		{"In Time", 12},
		{"Out Time", 12},
		{"Hours", 10},
		{"OT", 10},
		{"Late (min)", 12},
		{"Status", 12},
	}
	nCols := len(cols)

	thinBorder := []excelize.Border{
		{Type: "left", Color: "B0B7C3", Style: 1},
		{Type: "top", Color: "B0B7C3", Style: 1},
		{Type: "bottom", Color: "B0B7C3", Style: 1},
		{Type: "right", Color: "B0B7C3", Style: 1},
	}

	bandStyle, _ := f.NewStyle(&excelize.Style{
		Font:      &excelize.Font{Bold: true, Size: 15, Family: "Calibri", Color: "FFFFFF"},
		Fill:      excelize.Fill{Type: "pattern", Color: []string{"1D4E89"}, Pattern: 1},
		Alignment: &excelize.Alignment{Horizontal: "center", Vertical: "center"},
	})
	bandSubStyle, _ := f.NewStyle(&excelize.Style{
		Font:      &excelize.Font{Bold: true, Size: 12, Family: "Calibri", Color: "FFFFFF"},
		Fill:      excelize.Fill{Type: "pattern", Color: []string{"1D4E89"}, Pattern: 1},
		Alignment: &excelize.Alignment{Horizontal: "center", Vertical: "center"},
	})
	periodStyle, _ := f.NewStyle(&excelize.Style{
		Font:      &excelize.Font{Size: 11, Family: "Calibri", Color: "000000"},
		Alignment: &excelize.Alignment{Horizontal: "center", Vertical: "center"},
	})
	sectionLabelStyle, _ := f.NewStyle(&excelize.Style{
		Font:      &excelize.Font{Bold: true, Size: 11, Family: "Calibri", Color: "1D4E89"},
		Fill:      excelize.Fill{Type: "pattern", Color: []string{"DDEBF7"}, Pattern: 1},
		Alignment: &excelize.Alignment{Horizontal: "left", Vertical: "center"},
	})
	infoLabelStyle, _ := f.NewStyle(&excelize.Style{
		Font:      &excelize.Font{Bold: true, Size: 10, Family: "Calibri", Color: "595959"},
		Fill:      excelize.Fill{Type: "pattern", Color: []string{"F2F2F2"}, Pattern: 1},
		Border:    thinBorder,
		Alignment: &excelize.Alignment{Horizontal: "left", Vertical: "center"},
	})
	infoValueStyle, _ := f.NewStyle(&excelize.Style{
		Font:      &excelize.Font{Size: 10, Family: "Calibri", Color: "000000"},
		Border:    thinBorder,
		Alignment: &excelize.Alignment{Horizontal: "left", Vertical: "center"},
	})
	headerCellStyle, _ := f.NewStyle(&excelize.Style{
		Font:      &excelize.Font{Bold: true, Size: 11, Family: "Calibri", Color: "FFFFFF"},
		Fill:      excelize.Fill{Type: "pattern", Color: []string{"1D4E89"}, Pattern: 1},
		Border:    thinBorder,
		Alignment: &excelize.Alignment{Horizontal: "center", Vertical: "center", WrapText: true},
	})
	dataStyle, _ := f.NewStyle(&excelize.Style{
		Font:      &excelize.Font{Size: 10, Family: "Calibri", Color: "000000"},
		Border:    thinBorder,
		Alignment: &excelize.Alignment{Horizontal: "center", Vertical: "center"},
	})
	dataAltStyle, _ := f.NewStyle(&excelize.Style{
		Font:      &excelize.Font{Size: 10, Family: "Calibri", Color: "000000"},
		Fill:      excelize.Fill{Type: "pattern", Color: []string{"F2F5FA"}, Pattern: 1},
		Border:    thinBorder,
		Alignment: &excelize.Alignment{Horizontal: "center", Vertical: "center"},
	})
	redStyle, _ := f.NewStyle(&excelize.Style{
		Font:      &excelize.Font{Bold: true, Size: 10, Family: "Calibri", Color: "DC2626"},
		Fill:      excelize.Fill{Type: "pattern", Color: []string{"FEF2F2"}, Pattern: 1},
		Border:    thinBorder,
		Alignment: &excelize.Alignment{Horizontal: "center", Vertical: "center"},
	})
	greenStyle, _ := f.NewStyle(&excelize.Style{
		Font:      &excelize.Font{Bold: true, Size: 10, Family: "Calibri", Color: "16A34A"},
		Fill:      excelize.Fill{Type: "pattern", Color: []string{"F0FDF4"}, Pattern: 1},
		Border:    thinBorder,
		Alignment: &excelize.Alignment{Horizontal: "center", Vertical: "center"},
	})
	orangeStyle, _ := f.NewStyle(&excelize.Style{
		Font:      &excelize.Font{Bold: true, Size: 10, Family: "Calibri", Color: "EA580C"},
		Fill:      excelize.Fill{Type: "pattern", Color: []string{"FFF7ED"}, Pattern: 1},
		Border:    thinBorder,
		Alignment: &excelize.Alignment{Horizontal: "center", Vertical: "center"},
	})
	purpleStyle, _ := f.NewStyle(&excelize.Style{
		Font:      &excelize.Font{Bold: true, Size: 10, Family: "Calibri", Color: "4F46E5"},
		Fill:      excelize.Fill{Type: "pattern", Color: []string{"EEF2FF"}, Pattern: 1},
		Border:    thinBorder,
		Alignment: &excelize.Alignment{Horizontal: "center", Vertical: "center"},
	})
	grayStyle, _ := f.NewStyle(&excelize.Style{
		Font:      &excelize.Font{Bold: true, Size: 10, Family: "Calibri", Color: "64748B"},
		Fill:      excelize.Fill{Type: "pattern", Color: []string{"F1F5F9"}, Pattern: 1},
		Border:    thinBorder,
		Alignment: &excelize.Alignment{Horizontal: "center", Vertical: "center"},
	})
	summaryStyle, _ := f.NewStyle(&excelize.Style{
		Font:      &excelize.Font{Bold: true, Size: 10, Family: "Calibri", Color: "1D4E89"},
		Fill:      excelize.Fill{Type: "pattern", Color: []string{"DDEBF7"}, Pattern: 1},
		Alignment: &excelize.Alignment{Horizontal: "left", Vertical: "center"},
	})
	footerStyle, _ := f.NewStyle(&excelize.Style{
		Font:      &excelize.Font{Size: 9, Family: "Calibri", Color: "808080"},
		Alignment: &excelize.Alignment{Horizontal: "left", Vertical: "center"},
	})

	for i, col := range cols {
		f.SetColWidth(sheet, colNameAttendance(i+1), colNameAttendance(i+1), col.width)
	}
	endCol := colNameAttendance(nCols)

	// Row 1: company name (band)
	f.SetCellValue(sheet, "A1", companyName)
	f.MergeCell(sheet, "A1", endCol+"1")
	f.SetCellStyle(sheet, "A1", endCol+"1", bandStyle)
	f.SetRowHeight(sheet, 1, 28)

	// Row 2: report title (band)
	f.SetCellValue(sheet, "A2", "JOB CARD")
	f.MergeCell(sheet, "A2", endCol+"2")
	f.SetCellStyle(sheet, "A2", endCol+"2", bandSubStyle)
	f.SetRowHeight(sheet, 2, 22)

	// Row 3: period
	f.SetCellValue(sheet, "A3", "Period: "+period)
	f.MergeCell(sheet, "A3", endCol+"3")
	f.SetCellStyle(sheet, "A3", endCol+"3", periodStyle)
	f.SetRowHeight(sheet, 3, 18)

	// Row 4: blank
	f.SetRowHeight(sheet, 4, 6)

	// Row 5: employee information section label
	f.SetCellValue(sheet, "A5", "EMPLOYEE INFORMATION")
	f.MergeCell(sheet, "A5", endCol+"5")
	f.SetCellStyle(sheet, "A5", endCol+"5", sectionLabelStyle)
	f.SetRowHeight(sheet, 5, 20)

	// Rows 6-9: info grid (label, value, label, value)
	emp := sec.Employee
	name := emp.NameEn
	if name == "" {
		name = emp.NameBn
	}
	desig := ""
	if emp.DesignationRef != nil {
		desig = emp.DesignationRef.Name
		if desig == "" {
			desig = emp.DesignationRef.NameBn
		}
	}
	dept := ""
	if emp.Department != nil {
		dept = emp.Department.Name
		if dept == "" {
			dept = emp.Department.NameBn
		}
	}
	phone := emp.Phone
	joinDate := "-"
	if !emp.JoiningDate.IsZero() {
		joinDate = emp.JoiningDate.Format("02-01-2006")
	}
	shift := ""
	if len(sec.Rows) > 0 && sec.Rows[0].Shift != nil {
		shift = sec.Rows[0].Shift.Name
	}

	infoRows := [][4]string{
		{"Name", name, "Employee ID", emp.EmployeeID},
		{"Designation", desig, "Department", dept},
		{"Phone", phone, "Joining Date", joinDate},
		{"Shift", shift, "Days", strconv.Itoa(len(sec.Rows))},
	}
	for i, r := range infoRows {
		row := 6 + i
		f.SetCellValue(sheet, "A"+strconv.Itoa(row), r[0])
		f.SetCellValue(sheet, "B"+strconv.Itoa(row), r[1])
		f.SetCellValue(sheet, "C"+strconv.Itoa(row), r[2])
		f.SetCellValue(sheet, "D"+strconv.Itoa(row), r[3])
		f.MergeCell(sheet, "B"+strconv.Itoa(row), "B"+strconv.Itoa(row))
		f.MergeCell(sheet, "D"+strconv.Itoa(row), endCol+strconv.Itoa(row))
		f.SetCellStyle(sheet, "A"+strconv.Itoa(row), "A"+strconv.Itoa(row), infoLabelStyle)
		f.SetCellStyle(sheet, "B"+strconv.Itoa(row), "B"+strconv.Itoa(row), infoValueStyle)
		f.SetCellStyle(sheet, "C"+strconv.Itoa(row), "C"+strconv.Itoa(row), infoLabelStyle)
		f.SetCellStyle(sheet, "D"+strconv.Itoa(row), endCol+strconv.Itoa(row), infoValueStyle)
		f.SetRowHeight(sheet, row, 18)
	}

	// Row 10: blank
	f.SetRowHeight(sheet, 10, 6)

	// Row 11: table header
	headerRow := 11
	for i, col := range cols {
		cell := colNameAttendance(i+1) + strconv.Itoa(headerRow)
		f.SetCellValue(sheet, cell, col.header)
		f.SetCellStyle(sheet, cell, cell, headerCellStyle)
	}
	f.SetRowHeight(sheet, headerRow, 22)

	// Data rows
	dataStart := headerRow + 1
	for i, a := range sec.Rows {
		row := dataStart + i
		style := dataStyle
		if i%2 == 1 {
			style = dataAltStyle
		}
		cells := []string{
			strconv.Itoa(i + 1),
			jobCardDateDisplay(a.Date),
			jobCardDay(a.Date),
			shiftOf(a),
			jobCardClock(a.CheckIn),
			jobCardClock(a.CheckOut),
			strOrDash(a.TotalHours),
			strOrDash(a.OverTime),
			strconv.Itoa(a.LateMinutes),
			jobCardStatusCode(a.Status),
		}
		for ci, v := range cells {
			cell := colNameAttendance(ci+1) + strconv.Itoa(row)
			f.SetCellValue(sheet, cell, v)
			f.SetCellStyle(sheet, cell, cell, style)
		}
		statusCell := colNameAttendance(nCols) + strconv.Itoa(row)
		switch a.Status {
		case "absent":
			f.SetCellStyle(sheet, statusCell, statusCell, redStyle)
		case "present":
			f.SetCellStyle(sheet, statusCell, statusCell, greenStyle)
		case "late":
			f.SetCellStyle(sheet, statusCell, statusCell, orangeStyle)
		case "half_day":
			f.SetCellStyle(sheet, statusCell, statusCell, orangeStyle)
		case "on_leave", "leave":
			f.SetCellStyle(sheet, statusCell, statusCell, purpleStyle)
		case "weekend":
			f.SetCellStyle(sheet, statusCell, statusCell, grayStyle)
		}
		f.SetRowHeight(sheet, row, 19)
	}

	// Summary
	st := jobCardStatsFor(sec.Rows)
	summaryRow := dataStart + len(sec.Rows) + 1
	summaryLine1 := fmt.Sprintf("Summary:  Total Days: %d   |   Present: %d   |   Late: %d   |   Absent: %d   |   Half Day: %d",
		st.Total, st.Present, st.Late, st.Absent, st.HalfDay)
	summaryLine2 := fmt.Sprintf("Leave: %d   |   Weekend: %d   |   Holiday: %d   |   Late Minutes: %d",
		st.Leave, st.Weekend, st.Holiday, st.LateMinutes)
	f.SetCellValue(sheet, "A"+strconv.Itoa(summaryRow), summaryLine1)
	f.MergeCell(sheet, "A"+strconv.Itoa(summaryRow), endCol+strconv.Itoa(summaryRow))
	f.SetCellStyle(sheet, "A"+strconv.Itoa(summaryRow), endCol+strconv.Itoa(summaryRow), summaryStyle)
	f.SetRowHeight(sheet, summaryRow, 18)
	f.SetCellValue(sheet, "A"+strconv.Itoa(summaryRow+1), summaryLine2)
	f.MergeCell(sheet, "A"+strconv.Itoa(summaryRow+1), endCol+strconv.Itoa(summaryRow+1))
	f.SetCellStyle(sheet, "A"+strconv.Itoa(summaryRow+1), endCol+strconv.Itoa(summaryRow+1), summaryStyle)
	f.SetRowHeight(sheet, summaryRow+1, 18)

	// Footer
	footerRow := summaryRow + 3
	f.SetCellValue(sheet, "A"+strconv.Itoa(footerRow), "Generated by PeopleHub HR & Payroll System")
	f.MergeCell(sheet, "A"+strconv.Itoa(footerRow), endCol+strconv.Itoa(footerRow))
	f.SetCellStyle(sheet, "A"+strconv.Itoa(footerRow), endCol+strconv.Itoa(footerRow), footerStyle)
	f.SetCellValue(sheet, "A"+strconv.Itoa(footerRow+1), "Print Date: "+time.Now().Format("02-01-2006"))
	f.MergeCell(sheet, "A"+strconv.Itoa(footerRow+1), endCol+strconv.Itoa(footerRow+1))
	f.SetCellStyle(sheet, "A"+strconv.Itoa(footerRow+1), endCol+strconv.Itoa(footerRow+1), footerStyle)

	f.SetPanes(sheet, &excelize.Panes{
		Freeze:      true,
		XSplit:      0,
		YSplit:      dataStart - 1,
		TopLeftCell: "A" + strconv.Itoa(dataStart),
		ActivePane:  "bottomLeft",
	})
}

func shiftOf(a models.Attendance) string {
	if a.Shift != nil {
		return a.Shift.Name
	}
	return ""
}
