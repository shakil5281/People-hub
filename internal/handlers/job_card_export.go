func renderJobCardPDF(c *gin.Context, startDate, endDate, lang string, sections []jobCardSection) {
	labels := jobCardEnLabels
	if lang == "bn" {
		labels = jobCardBnLabels
	}

	pdf := gofpdf.New("P", "mm", "A4", "")
	pdf.SetMargins(10, 10, 10)
	pdf.SetAutoPageBreak(false, 0)
	font := loadBanglaFont(pdf)

	company := models.Company{}
	if len(sections) > 0 && len(sections[0].Rows) > 0 {
		company = sections[0].Rows[0].Employee.Company
	}
	period := jobCardPeriod(startDate, endDate)

	for _, sec := range sections {
		pdf.AddPage()
		drawJobCardPage(pdf, font, labels, company, period, sec)
	}

	filename := fmt.Sprintf("job_card_%s_%s.pdf", startDate, endDate)
	if len(sections) == 1 {
		filename = fmt.Sprintf("job_card_%s_%s_%s.pdf", sections[0].Employee.EmployeeID, startDate, endDate)
	}
	c.Header("Content-Type", "application/pdf")
	c.Header("Content-Disposition", fmt.Sprintf("attachment; filename=%s", filename))
	if err := pdf.Output(c.Writer); err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"error": "Failed to generate PDF"})
	}
}

func drawJobCardPage(pdf *gofpdf.Fpdf, font string, labels jobCardLabels, company models.Company, period string, sec jobCardSection) {
	drawJobCardCompanyHeader(pdf, font, labels, company, period)
	drawJobCardInfo(pdf, font, labels, sec)
	drawJobCardTable(pdf, font, labels, sec.Rows)
	drawJobCardSummary(pdf, font, labels, sec.Rows)
	drawJobCardFooter(pdf, font, labels)
}

func drawJobCardCompanyHeader(pdf *gofpdf.Fpdf, font string, labels jobCardLabels, company models.Company, period string) {
	companyName := companyDisplayName(company)
	pdf.SetFillColor(29, 78, 137)
	pdf.Rect(0, 0, 210, 22, "F")
	pdf.SetTextColor(255, 255, 255)
	pdf.SetFont(font, "B", 13)
	pdf.SetXY(10, 3.5)
	pdf.CellFormat(190, 6, companyName, "", 0, "C", false, 0, "")
	pdf.SetFont(font, "B", 10)
	pdf.SetXY(10, 10.5)
	pdf.CellFormat(190, 5, labels.JobCardTitle, "", 0, "C", false, 0, "")
	pdf.SetFont(font, "", 8)
	pdf.SetXY(10, 16.5)
	pdf.CellFormat(190, 4, labels.PeriodLabel+": "+period, "", 0, "C", false, 0, "")
	pdf.SetTextColor(0, 0, 0)
	pdf.SetY(26)
}

func drawJobCardInfo(pdf *gofpdf.Fpdf, font string, labels jobCardLabels, sec jobCardSection) {
	emp := sec.Employee
	y := pdf.GetY()

	pdf.SetFont(font, "B", 8)
	pdf.SetTextColor(29, 78, 137)
	pdf.SetXY(10, y)
	pdf.CellFormat(190, 4, labels.EmployeeInfo, "", 0, "L", false, 0, "")
	pdf.SetDrawColor(29, 78, 137)
	pdf.SetLineWidth(0.3)
	pdf.Line(10, y+4.5, 200, y+4.5)
	y += 7

	name := emp.NameEn
	if name == "" {
		name = emp.NameBn
	}
	desig := ""
	if emp.DesignationRef != nil {
		desig = emp.DesignationRef.Name
		if desig == "" {
			desig = emp.DesignationRef.NameBn
		}
	}
	dept := ""
	if emp.Department != nil {
		dept = emp.Department.Name
		if dept == "" {
			dept = emp.Department.NameBn
		}
	}
	phone := emp.Phone
	joinDate := "-"
	if !emp.JoiningDate.IsZero() {
		joinDate = emp.JoiningDate.Format("02-01-2006")
	}
	shift := ""
	if len(sec.Rows) > 0 && sec.Rows[0].Shift != nil {
		shift = sec.Rows[0].Shift.Name
	}

	pairs := [][2]string{
		{labels.Name, name},
		{labels.EmployeeID, emp.EmployeeID},
		{labels.Designation, desig},
		{labels.Department, dept},
		{labels.Phone, phone},
		{labels.JoiningDate, joinDate},
		{labels.Shift, shift},
		{labels.TotalDays, strconv.Itoa(len(sec.Rows))},
	}

	labelW := 30.0
	valW := 65.0
	rowH := 5.6
	for i, p := range pairs {
		col := i % 2
		rowIdx := i / 2
		x := 10.0
		if col == 1 {
			x = 105.0
		}
		ry := y + float64(rowIdx)*rowH
		pdf.SetFont(font, "B", 8)
		pdf.SetTextColor(90, 90, 90)
		pdf.SetXY(x, ry)
		pdf.CellFormat(labelW, rowH-1, p[0], "", 0, "L", false, 0, "")
		pdf.SetFont(font, "", 8.5)
		pdf.SetTextColor(0, 0, 0)
		pdf.SetXY(x+labelW, ry)
		pdf.CellFormat(valW, rowH-1, p[1], "", 0, "L", false, 0, "")
	}
	pdf.SetY(y + 4*rowH + 3)
}

func drawJobCardTable(pdf *gofpdf.Fpdf, font string, labels jobCardLabels, rows []models.Attendance) {
	x0 := 10.0
	widths := []float64{8, 24, 14, 24, 20, 20, 16, 16, 22, 26}
	headers := []string{labels.Sl, labels.Date, labels.Day, labels.Shift, labels.InTime, labels.OutTime, labels.Hours, labels.OT, labels.LateMinutes, labels.Status}
	rowH := 6.0
	pageH := 297.0
	bottom := 34.0

	y := pdf.GetY()
	drawJobCardTableHeader(pdf, font, x0, y, widths, headers)
	y += rowH

	for i, a := range rows {
		if y+rowH > pageH-bottom {
			pdf.AddPage()
			y = 10
			drawJobCardTableHeader(pdf, font, x0, y, widths, headers)
			y += rowH
		}
		drawJobCardTableRow(pdf, font, x0, y, widths, i+1, a)
		y += rowH
	}
	pdf.SetY(y)
}

func drawJobCardTableHeader(pdf *gofpdf.Fpdf, font string, x0, y float64, widths []float64, headers []string) {
	pdf.SetFillColor(29, 78, 137)
	pdf.SetTextColor(255, 255, 255)
	pdf.SetFont(font, "B", 7.5)
	cx := x0
	for i, h := range headers {
		pdf.Rect(cx, y, widths[i], 6, "F")
		pdf.SetXY(cx, y+0.5)
		pdf.CellFormat(widths[i], 5, h, "", 0, "C", false, 0, "")
		cx += widths[i]
	}
	pdf.SetTextColor(0, 0, 0)
}

func drawJobCardTableRow(pdf *gofpdf.Fpdf, font string, x0, y float64, widths []float64, idx int, a models.Attendance) {
	shift := ""
	if a.Shift != nil {
		shift = a.Shift.Name
	}
	cells := []string{
		strconv.Itoa(idx),
		jobCardDateDisplay(a.Date),
		jobCardDay(a.Date),
		shift,
		jobCardClock(a.CheckIn),
		jobCardClock(a.CheckOut),
		strOrDash(a.TotalHours),
		strOrDash(a.OverTime),
		strconv.Itoa(a.LateMinutes),
		jobCardStatusCode(a.Status),
	}

	if idx%2 == 0 {
		pdf.SetFillColor(244, 246, 250)
	} else {
		pdf.SetFillColor(255, 255, 255)
	}
	pdf.SetDrawColor(200, 208, 220)
	pdf.SetLineWidth(0.15)

	tc := [3]int{0, 0, 0}
	switch a.Status {
	case "absent":
		tc = [3]int{220, 38, 38}
	case "present":
		tc = [3]int{22, 163, 74}
	case "late":
		tc = [3]int{234, 88, 12}
	case "half_day":
		tc = [3]int{202, 138, 4}
	case "on_leave", "leave":
		tc = [3]int{79, 70, 229}
	case "weekend":
		tc = [3]int{100, 116, 139}
	}

	cx := x0
	pdf.SetFont(font, "", 8)
	for i, cell := range cells {
		pdf.Rect(cx, y, widths[i], 6, "F")
		pdf.Rect(cx, y, widths[i], 6, "D")
		cur := tc
		if i != 9 {
			cur = [3]int{0, 0, 0}
		}
		pdf.SetTextColor(cur[0], cur[1], cur[2])
		pdf.SetXY(cx, y+0.5)
		pdf.CellFormat(widths[i], 5, cell, "", 0, "C", false, 0, "")
		cx += widths[i]
	}
	pdf.SetTextColor(0, 0, 0)
}

