type jobCardSection struct {
	Employee models.Employee
	Rows     []models.Attendance
}

type jobCardStats struct {
	Total, Present, Late, Absent, HalfDay, Leave, Weekend, Holiday, LateMinutes int
}

func groupJobCard(atts []models.Attendance) []jobCardSection {
	var sections []jobCardSection
	for _, a := range atts {
		if len(sections) == 0 || sections[len(sections)-1].Employee.EmployeeID != a.EmployeeID {
			sections = append(sections, jobCardSection{Employee: a.Employee})
		}
		last := &sections[len(sections)-1]
		last.Rows = append(last.Rows, a)
	}
	return sections
}

func jobCardStatsFor(rows []models.Attendance) jobCardStats {
	var st jobCardStats
	st.Total = len(rows)
	for _, a := range rows {
		switch a.Status {
		case "present":
			st.Present++
		case "late":
			st.Late++
		case "absent":
			st.Absent++
		case "half_day":
			st.HalfDay++
		case "on_leave", "leave":
			st.Leave++
		case "weekend":
			st.Weekend++
		case "holiday":
			st.Holiday++
		}
		st.LateMinutes += a.LateMinutes
	}
	return st
}

func jobCardStatusCode(s string) string {
	switch s {
	case "present":
		return "P"
	case "late":
		return "L"
	case "absent":
		return "A"
	case "half_day":
		return "HD"
	case "on_leave", "leave":
		return "V"
	case "weekend":
		return "W"
	case "holiday":
		return "H"
	}
	if s == "" {
		return "-"
	}
	return strings.ToUpper(s[:1])
}

func jobCardDateDisplay(dateStr string) string {
	t, err := time.Parse("2006-01-02", dateStr)
	if err != nil {
		t, err = time.Parse("2006-01-02T15:04:05Z", dateStr)
	}
	if err != nil {
		t, err = time.Parse("2006-01-02T15:04:05", dateStr)
	}
	if err != nil {
		return dateStr
	}
	return t.Format("02 Jan 2006")
}

func jobCardDay(dateStr string) string {
	t, err := time.Parse("2006-01-02", dateStr)
	if err != nil {
		t, err = time.Parse("2006-01-02T15:04:05Z", dateStr)
	}
	if err != nil {
		t, err = time.Parse("2006-01-02T15:04:05", dateStr)
	}
	if err != nil {
		return "-"
	}
	return t.Format("Mon")
}

func jobCardClock(t *time.Time) string {
	if t == nil {
		return "-"
	}
	return t.Format("15:04")
}

func jobCardPeriod(start, end string) string {
	s, _ := time.Parse("2006-01-02", start)
	e, _ := time.Parse("2006-01-02", end)
	if s.IsZero() || e.IsZero() {
		return start + " - " + end
	}
	return s.Format("02-01-2006") + " - " + e.Format("02-01-2006")
}

func strOrDash(s *string) string {
	if s == nil || *s == "" {
		return "-"
	}
	return *s
}

// ExportJobCard godoc
//
//	@Summary      Export job card (PDF / Excel)
//	@Description  Export employee job card attendance records to PDF or Excel. When employee_id is empty all filtered employees are exported, grouped by employee.
//	@Tags         Attendance
//	@Security     BearerAuth
//	@Produce      application/octet-stream
//	@Param        format         query string false "Export format: pdf (default) or excel"
//	@Param        lang           query string false "PDF language: en (default) or bn"
//	@Param        start_date     query string false "Start date (YYYY-MM-DD)"
//	@Param        end_date       query string false "End date (YYYY-MM-DD)"
//	@Param        company_id     query string false "Filter by company"
//	@Param        employee_id    query string false "Filter by employee"
//	@Param        department_id  query string false "Filter by department"
//	@Param        section_id     query string false "Filter by section"
//	@Param        designation_id query string false "Filter by designation"
//	@Param        line_id        query string false "Filter by line"
//	@Param        group_id       query string false "Filter by group"
//	@Param        shift_id       query string false "Filter by shift"
//	@Param        status         query string false "Filter by status"
//	@Success      200  {file}  binary
//	@Failure      500  {object}  map[string]string
//	@Router       /attendance/job-card/export [get]
func (h *AttendanceHandler) ExportJobCard(c *gin.Context) {
	startDate := c.DefaultQuery("start_date", time.Now().Format("2006-01-02"))
	endDate := c.DefaultQuery("end_date", time.Now().Format("2006-01-02"))
	format := c.DefaultQuery("format", "pdf")
	lang := c.DefaultQuery("lang", "en")
	companyID := c.Query("company_id")
	employeeID := c.Query("employee_id")
	departmentID := c.Query("department_id")
	sectionID := c.Query("section_id")
	designationID := c.Query("designation_id")
	lineID := c.Query("line_id")
	groupID := c.Query("group_id")
	shiftID := c.Query("shift_id")
	status := c.Query("status")

	if employeeID != "" {
		emp, err := h.employeeRepo.FindByEmployeeID(employeeID)
		if err != nil {
			emp, err = h.employeeRepo.FindByPunchNumber(employeeID)
		}
		if err == nil && emp != nil {
			employeeID = emp.EmployeeID
		}
	}

	endDate = capEndDateToSeparation(h, employeeID, endDate)

	attendances, _, err := h.attendanceRepo.ListJobCard(startDate, endDate, companyID, employeeID, departmentID, sectionID, designationID, lineID, groupID, shiftID, status, 1, 100000)
	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		return
	}

	sections := groupJobCard(attendances)

	switch format {
	case "excel":
		renderJobCardExcel(c, startDate, endDate, sections)
	default:
		renderJobCardPDF(c, startDate, endDate, lang, sections)
	}
}

func capEndDateToSeparation(h *AttendanceHandler, employeeID, endDate string) string {
	if employeeID == "" {
		return endDate
	}
	sep, err := h.separationRepo.FindProcessedByEmployeeID(employeeID)
	if err == nil && sep != nil && sep.Date != "" {
		sepDate, parseErr := time.Parse("2006-01-02", sep.Date)
		endDateParsed, endParseErr := time.Parse("2006-01-02", endDate)
		if parseErr == nil && endParseErr == nil {
			dayBeforeSep := sepDate.AddDate(0, 0, -1)
			if dayBeforeSep.Before(endDateParsed) {
				return dayBeforeSep.Format("2006-01-02")
			}
		}
	}
	return endDate
}

